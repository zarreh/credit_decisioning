"""``make docs-assets``: plots and the results page, generated from the committed evidence.

Writes docs/assets/plots/{light,dark}/*.png and docs/evidence/results.md. Nothing here
is typed by hand, so the docs cannot drift from artifacts/evidence.json; CI checks that
re-running this produces no diff.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = json.loads((ROOT / "artifacts/evidence.json").read_text())
REPORT = json.loads((ROOT / "artifacts/verifier_report.json").read_text())
THEMES = {
    "light": {"bg": "#ffffff", "fg": "#0f172a", "grid": "#e2e8f0", "accent": "#0d9488", "muted": "#94a3b8"},
    "dark": {"bg": "#0f172a", "fg": "#e2e8f0", "grid": "#1e293b", "accent": "#2dd4bf", "muted": "#64748b"},
}


def _style(ax: Any, t: dict[str, str]) -> None:
    ax.set_facecolor(t["bg"])
    ax.tick_params(colors=t["fg"])
    for spine in ax.spines.values():
        spine.set_color(t["grid"])
    ax.grid(color=t["grid"], linewidth=0.6)
    ax.xaxis.label.set_color(t["fg"])
    ax.yaxis.label.set_color(t["fg"])
    ax.title.set_color(t["fg"])


def reliability(t: dict[str, str], out: Path) -> None:
    bins = EVIDENCE["reliability"]
    fig, ax = plt.subplots(figsize=(5, 4), facecolor=t["bg"])
    ax.plot([0, 1], [0, 1], color=t["muted"], linestyle="--", linewidth=1, label="perfect calibration")
    ax.plot(
        [b["mean_predicted"] for b in bins],
        [b["observed"] for b in bins],
        marker="o",
        color=t["accent"],
        label="champion (pooled out-of-fold)",
    )
    for b in bins:
        ax.annotate(
            f"n={b['n']}",
            (b["mean_predicted"], b["observed"]),
            fontsize=7,
            color=t["muted"],
            xytext=(4, -10),
            textcoords="offset points",
        )
    ax.set_xlabel("predicted probability of bad")
    ax.set_ylabel("observed bad rate")
    ax.set_title(f"Reliability, n = {EVIDENCE['provenance']['n']}")
    _style(ax, t)
    ax.legend(facecolor=t["bg"], edgecolor=t["grid"], labelcolor=t["fg"], fontsize=8)
    fig.tight_layout()
    fig.savefig(out, dpi=130, metadata={"Software": None})
    plt.close(fig)


def fairness_age(t: dict[str, str], out: Path) -> None:
    rows = sorted(EVIDENCE["fairness"]["age_band"], key=lambda r: r["group"])
    fig, ax = plt.subplots(figsize=(5.5, 3.2), facecolor=t["bg"])
    for i, r in enumerate(rows):
        if r["status"] != "ok":
            ax.text(0.02, i, f"insufficient n (n={r['n']})", va="center", color=t["muted"], fontsize=8)
            continue
        lo, hi = r["ci95"]["approval_rate"]
        ax.plot([lo, hi], [i, i], color=t["accent"], linewidth=6, alpha=0.35, solid_capstyle="round")
        ax.plot(r["approval_rate"], i, "|", color=t["accent"], markersize=14, markeredgewidth=2)
    ax.set_yticks(range(len(rows)), [f"{r['group']} (n={r['n']})" for r in rows])
    ax.set_xlim(0, 1)
    ax.set_xlabel("approval rate at the 1/6 threshold (95% CI)")
    ax.set_title("Approval rate by age band (age is not a model input)")
    _style(ax, t)
    fig.tight_layout()
    fig.savefig(out, dpi=130, metadata={"Software": None})
    plt.close(fig)


def _ci(m: dict[str, Any], d: int = 3) -> str:
    return f"{m['estimate']:.{d}f} [{m['ci95'][0]:.{d}f}, {m['ci95'][1]:.{d}f}]"


def results_md() -> str:
    e, p = EVIDENCE, EVIDENCE["provenance"]
    lines = [
        "<!-- GENERATED by docs/generate_plots.py from artifacts/*.json. Do not edit. -->",
        "# Results",
        "",
        f"**n** = {p['n']} ({p['n_bad']} bad) · **labels**: {p['label_source']} · **scorer**: {p['scorer']} · "
        f"**model**: {p['model_version']} · **run date**: {p['run_date']} · **uncertainty**: {p['uncertainty']} · "
        f"**validation**: {p['validation']}",
        "",
        "## Model",
        "",
        "| Metric (95% CI) | Champion | Challenger | Spread across repeats (champion) |",
        "|---|---|---|---|",
    ]
    for key, name in [
        ("auroc", "AUROC"),
        ("expected_cost", "Expected cost per applicant"),
        ("brier", "Brier score"),
        ("ece", "ECE (10 bins)"),
    ]:
        c, h = e["champion"][key], e["challenger"][key]
        lines.append(f"| {name} | {_ci(c)} | {_ci(h)} | {c['repeat_range'][0]:.3f} to {c['repeat_range'][1]:.3f} |")
    d = e["challenger_minus_champion"]
    lines += [
        "",
        f"Trivial baselines: approve everyone **{e['baselines']['approve_everyone']:.2f}**, decline everyone "
        f"**{e['baselines']['decline_everyone']:.2f}** per applicant.",
        "",
        f"Challenger minus champion (paired bootstrap): AUROC {_ci(d['auroc'])}; "
        f"expected cost {_ci(d['expected_cost'])}.",
        "",
        f"Policy: threshold {e['policy']['threshold']:.4f}, refer ceiling {e['policy']['refer_ceiling']}; "
        "out-of-fold band counts " + ", ".join(f"{k} {v}" for k, v in e["policy"]["band_counts"].items()) + ".",
        "",
        f"Serving model: fitted on n = {e['serving_model']['fitted_on_n']}; attribution reference "
        f"`{e['serving_model']['reference_kind']}` (n = {e['serving_model']['reference_n']}); calibration slope "
        f"{e['serving_model']['calibration_slope']:.3f} (negative = monotone increasing).",
        "",
        "![Reliability](../assets/plots/light/reliability.png#only-light)",
        "![Reliability](../assets/plots/dark/reliability.png#only-dark)",
        "",
        "## Fairness (pooled out-of-fold, binary policy)",
        "",
    ]
    for attribute, rows in e["fairness"].items():
        proxy = e["proxy_audit"][attribute]
        lines += [
            f"### {attribute.replace('_', ' ')}",
            "",
            f"Proxy audit ({proxy['method']}): AUROC {_ci(proxy['auroc'], 2)}.",
            "",
            "| Group | n (bad) | Approval rate [95% CI] | Impact ratio | FPR | FNR | Calibration gap |",
            "|---|---|---|---|---|---|---|",
        ]
        for r in rows:
            if r["status"] != "ok":
                lines.append(f"| {r['group']} | {r['n']} ({r['n_bad']}) | insufficient n | | | | |")
                continue
            lo, hi = r["ci95"]["approval_rate"]
            lines.append(
                f"| {r['group']} | {r['n']} ({r['n_bad']}) | {r['approval_rate']:.3f} [{lo:.3f}, {hi:.3f}] | "
                f"{r['adverse_impact_ratio']:.2f} | {r['false_positive_rate']:.3f} | {r['false_negative_rate']:.3f} | "
                f"{r['calibration_gap']:+.3f} |"
            )
        lines.append("")
    lines += [
        "![Approval by age](../assets/plots/light/fairness_age.png#only-light)",
        "![Approval by age](../assets/plots/dark/fairness_age.png#only-dark)",
        "",
        "## Verifier",
        "",
        f"**n** = {REPORT['verifier']['genuine_notices']} genuine notices · **labels**: {REPORT['label_source']} · "
        f"**scorer**: {REPORT['scorer']} · **model**: {REPORT['model_version']} · **run date**: {REPORT['run_date']} · "
        "**uncertainty**: a finite test count, not an error-rate estimate",
        "",
        f"False rejects of genuine notices: **{REPORT['verifier']['false_rejects']}**.",
        "",
        "| Mutator | Defect | Intended check(s) | Killed / applicable | Not applicable |",
        "|---|---|---|---|---|",
    ]
    for mid, m in REPORT["verifier"]["mutators"].items():
        checks = ", ".join(f"`{c}`" for c in m["intended_checks"])
        lines.append(f"| {mid} | {m['defect']} | {checks} | {m['killed']} / {m['applicable']} | {m['skipped']} |")
    detected = sum(v == "detected" for v in REPORT["meta_mutation"].values())
    a = REPORT["analyst"]
    lines += [
        "",
        f"Meta-mutation: {detected} of {len(REPORT['meta_mutation'])} checks, when disabled, made the gate fail.",
        "",
        "## Analyst guard rails",
        "",
        f"**n** = {a['n']} cases · **labels**: {a['label_source']} · **scorer**: {a['scorer']} · "
        f"**model**: {a['model_version']} "
        f"· passed **{a['passed']} / {a['n']}**. This measures the code around the model, not a live model's answers.",
        "",
        "| Case | Job | Passed |",
        "|---|---|---|",
    ]
    lines += [f"| {cid} | {c['job']} | {'yes' if c['passed'] else 'no'} |" for cid, c in a["cases"].items()]
    return "\n".join(lines) + "\n"


def main() -> None:
    for name, theme in THEMES.items():
        out = ROOT / "docs/assets/plots" / name
        out.mkdir(parents=True, exist_ok=True)
        reliability(theme, out / "reliability.png")
        fairness_age(theme, out / "fairness_age.png")
    (ROOT / "docs/evidence/results.md").write_text(results_md())
    print("docs assets regenerated")


if __name__ == "__main__":
    main()
